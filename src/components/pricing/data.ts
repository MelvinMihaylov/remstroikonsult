export const pricingRoute = "/prices";

const pricingSlugLookup = new Map<string, string>();

for (const category of pricingCategories) {
  pricingSlugLookup.set(category.slug, category.slug);

  for (const legacySlug of category.legacySlugs ?? []) {
    pricingSlugLookup.set(legacySlug, category.slug);
  }
}

export function resolvePricingCategorySlug(slug: string | null | undefined) {
  const candidate = slug?.trim();
  if (!candidate) {
    return null;
  }

  return pricingSlugLookup.get(candidate) ?? null;
}

export const defaultPricingCategorySlug = pricingCategories[0]?.slug ?? "finishing-works";
